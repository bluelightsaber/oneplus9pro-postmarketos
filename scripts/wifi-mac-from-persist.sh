#!/bin/sh
# Run ON THE PHONE as root: give wlan0 (ath11k) the phone's real Wi-Fi MAC (persist wlan_mac.bin, Intf0) via a
# systemd .link file. The MAC is never printed.
set -e
Q=$(mktemp -d)
mount -o ro,noexec,nosuid,nodev /dev/disk/by-partlabel/persist "$Q"
RAW=$(sed -n 's/^Intf0MacAddress=\([0-9A-Fa-f]\{12\}\).*/\1/p' "$Q/wlan_mac.bin" | head -1)
umount "$Q"; rmdir "$Q"
[ ${#RAW} -eq 12 ] || { echo "no Intf0MacAddress in persist wlan_mac.bin"; exit 1; }
MAC=$(echo "$RAW" | tr 'A-F' 'a-f' | sed 's/../&:/g; s/:$//')
mkdir -p /etc/systemd/network
cat > /etc/systemd/network/10-wlan0-persist-mac.link <<L
# OnePlus 9 Pro: real Wi-Fi MAC from persist/wlan_mac.bin (generated by wifi-mac-from-persist.sh)
[Match]
Driver=ath11k_pci

[Link]
MACAddress=$MAC
NamePolicy=kernel
L
chmod 644 /etc/systemd/network/10-wlan0-persist-mac.link
echo "written /etc/systemd/network/10-wlan0-persist-mac.link (OUI $(echo $MAC | cut -c1-8))"
