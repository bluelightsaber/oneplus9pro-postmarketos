#!/usr/bin/env python3
"""Derive ~/update-pmos-kernel-phymux.sh (TEST kernel, never promoted) from ~/update-pmos-kernel.sh:
adds patch 0106 (gcc-sm8350 usb3 pipe clk phy_mux), lockdown off (production modules load unsigned-key),
then builds RAM test images for USB 3 DT stages b and c1 and exits."""
import os, sys
home = os.path.expanduser("~")
s = open(f"{home}/update-pmos-kernel.sh").read()

def ins_after(anchor, text):
    global s
    if s.count(anchor) != 1:
        sys.exit("anchor: " + anchor)
    s = s.replace(anchor, anchor + text)

ins_after('sudo git diff --no-color -- $FP > /tmp/femto.patch; sudo git checkout -q -- $FP\n',
"""# 0106 (TEST): gcc-sm8350 usb3_prim pipe clock source as clk_regmap_phy_mux (park on XO while the PHY is off)
GF=drivers/clk/qcom/gcc-sm8350.c; sudo git checkout -q -- $GF
sudo python3 $P/scripts/apply-gcc-sm8350-usb3-phy-mux.py $GF || die "gcc phy_mux patch does not apply to $TAG"
sudo git diff --no-color -- $GF > /tmp/gccmux.patch; sudo git checkout -q -- $GF
""")
ins_after('cp /tmp/femto.patch $D/0105-phy-qcom-snps-femto-v2-host-release-utmi-override.patch\n',
"cp /tmp/gccmux.patch $D/0106-clk-qcom-gcc-sm8350-usb3-prim-pipe-phy-mux.patch\n")
ins_after('grep -q "0105-phy-qcom" $D/APKBUILD || die "could not add 0105 to the APKBUILD"\n',
"""sed -i "0,/0105-phy-qcom-snps-femto-v2-host-release-utmi-override.patch/s|0105-phy-qcom-snps-femto-v2-host-release-utmi-override.patch|&\\n\\t0106-clk-qcom-gcc-sm8350-usb3-prim-pipe-phy-mux.patch|" $D/APKBUILD
grep -q "0106-clk-qcom" $D/APKBUILD || die "could not add 0106 to the APKBUILD"
""")
a = 'pmbootstrap checksum linux-postmarketos-mainline'
if s.count(a) != 1: sys.exit("anchor checksum")
s = s.replace(a, """# TEST ONLY: no forced lockdown, so the production modules (other signing key) still load; never promote
sed -i "/CONFIG_LOCK_DOWN_KERNEL_FORCE_/d" $CF; echo "CONFIG_LOCK_DOWN_KERNEL_FORCE_NONE=y" >> $CF
""" + a)
b = 'echo "built $(date +%T)"\n'
i = s.find(b)
if i < 0: sys.exit("anchor built")
s = s[:i + len(b)] + """pmbootstrap chroot -b aarch64 -- apk del -q linux-postmarketos-lts linux-postmarketos-stable >/dev/null 2>&1
sudo cp ~/usb3-dt.sh $V/usb3-dt.sh
for ST in b c1; do
  USB3=0 NAME=phymux-$ST SKIPMODS=1 EXTRA_UCMD="sh /home/pmos/v2/usb3-dt.sh \\$D $ST" ~/build-pmos-image.sh linux-postmarketos-mainline 2>&1 | grep -vE "^\\[" | tail -3
done
echo PHYMUX-DONE; exit 0
"""
s = s.replace("# Update cycle for the production kernel", "# TEST kernel (generated by mk-phymux-script.py, never promote). Based on the update cycle for the production kernel", 1)
open(f"{home}/update-pmos-kernel-phymux.sh", "w").write(s)
os.chmod(f"{home}/update-pmos-kernel-phymux.sh", 0o755)
print("ok")
